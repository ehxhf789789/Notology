/**
 * 마크다운의 **꾸밈을 걷은 알맹이** — 충돌 검사에서만 쓴다.
 *
 * 한빈: *"「이 노트가 다른 기기에서 수정되었습니다」가 노트 창을 여니까 왜 매번
 * 뜨는건가?"* — 다른 기기가 고친 것이 아니었다. dobbin 과 이 앱이 **같은 글을
 * 서로 다르게 적어서**다:
 *
 *   ① dobbin 이 색 칩을 쓴다   <span style='color:#6f9e7a;…'>종류</span> 세미나 자료
 *      🔴 서가 노트 382/420 (90%) 이 이것을 갖는다 (실측 2026-09-04)
 *   ② TipTap 직렬화기가 못 되돌려 쓴다   → **종류** 세미나 자료 · `_` → `\_`
 *   ③ 그래서 on('update') 가 돌아 **사람이 한 글자도 안 쳤는데 dirty** 가 된다
 *   ④ 그 상태로 충돌 검사가 raw 문자열을 견주니 늘 다르다 → 배너
 *   ⑤ 창을 열 때마다 ①~④ 가 되풀이 → **매번 뜬다**
 *
 * 🔴 **새 규약이 아니다.** 같은 파일의 재적재 갈래는 이미 「Phantom change」라는
 *    이름으로 이 일을 한다 (`useContentLoader.ts` 의 `cached.body === currentBody`).
 *    충돌 갈래에만 그 눈이 없었다.
 *
 * ⚠️ **충돌 검사에서만 쓴다.** 강조 기호까지 걷으므로, 사람이 진짜로 `**강조**`
 *    를 지운 것도 「같다」가 된다. 저장·비교의 다른 자리에 쓰면 진짜 편집을
 *    삼킨다.
 */
export function markdownShape(text: string): string {
  return (text || '')
    // 🔴 `<br>` 은 **지우지 않고 줄바꿈으로** — 앱이 하드브레이크로 되쓴다.
    //    지우면 디스크는 한 줄인데 앱은 두 줄이라 표 셀 안의 `<br>` 이
    //    영영 「다르다」가 된다 (서가 2장 · 실측 2026-09-04).
    .replace(/<br\s*\/?>/gi, '\n')
    // 인라인 HTML 벗기기 — 알맹이 글자는 남긴다 (`<span …>종류</span>` → `종류`)
    .replace(/<[^>]+>/g, '')
    // 마크다운 이스케이프 풀기 (`\_` → `_` · `1\.` → `1.`)
    .replace(/\\([\\`*_{}[\]()#+\-.!~|])/g, '$1')
    // 강조 기호 걷기 (`**종류**` → `종류`)
    // 🔴 두 가지를 일부러 좁혔다 — 넓게 잡았더니 실측에서 되레 못 걷었다:
    //   ⓐ `[^\n]` — 줄을 넘지 않는다. `[\s\S]` 로 두었더니 앞줄의 `_` 가
    //      뒷줄의 `_` 와 짝지어 그 사이를 통째로 삼켜, **안쪽 `**` 가 못 걸렸다**
    //   ⓑ `_`·`__` 는 안 본다. 한국어 태그(`key/시설물_상태_기록`)와 경로
    //      (`02_Projects`)가 밑줄을 낱말 안에 쓴다 — 강조로 읽으면 글자를 먹는다
    .replace(/(\*\*|\*)(?=\S)([^\n]*?\S)\1/g, '$2')
    // 탭·여러 공백 → 하나
    .replace(/[ \t]+/g, ' ')
    // 줄 앞뒤 공백
    .split('\n').map(l => l.trim()).join('\n')
    // 빈 줄 여러 개 → 하나
    .replace(/\n{2,}/g, '\n')
    .trim();
}

/** 두 글이 **꾸밈만 다른가**. 같으면 충돌이 아니다. */
export function looksSame(a: string, b: string): boolean {
  return markdownShape(a) === markdownShape(b);
}
